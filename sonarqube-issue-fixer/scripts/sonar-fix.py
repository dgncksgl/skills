def pmd_ruleset(data: dict) -> str:
    rules = []
    for name, (_, category) in data["pmd"].items():
        if name == "AvoidDuplicateLiterals":
            rules.append(f'<rule ref="{category}/{name}"><properties><property name="maxDuplicateLiterals" value="{DUPLICATE_LITERAL_THRESHOLD}"/>'
                         f'<property name="minimumLength" value="{DUPLICATE_LITERAL_MIN_LENGTH}"/>'
                         f'<property name="skipAnnotations" value="true"/></properties></rule>')
        else:
            rules.append(f'<rule ref="{category}/{name}"/>')
    return ('<?xml version="1.0"?>\n<ruleset name="sonar-equivalent" xmlns="http://pmd.sourceforge.net/ruleset/2.0.0" '
            'xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance" xsi:schemaLocation="http://pmd.sourceforge.net/ruleset/2.0.0 '
            'https://pmd.sourceforge.io/ruleset_2_0_0.xsd">\n<description>Sonar way equivalents</description>\n'
            + "\n".join(rules) + "\n</ruleset>\n")


PMD_SUPPRESSION_PATTERN = re.compile(r'(@(?:java\.lang\.)?SuppressWarnings\s*\()([^)]*)(\))')


def without_pmd_suppressions(text: str) -> str:
    """Neutralises "PMD" / "PMD.Rule" keys inside @SuppressWarnings, keeping every line and column (SonarQube ignores them)."""
    return PMD_SUPPRESSION_PATTERN.sub(lambda match: match.group(1) + match.group(2).replace('"PMD', '"XMD') + match.group(3), text)


def pmd_sources(root: Path, files: List[str], copies: Path) -> Dict[str, str]:
    """Absolute path to give PMD -> project-relative path; files with PMD suppressions or a comma in the path are analysed as copies."""
    sources: Dict[str, str] = {}
    for relative in files:
        text = read_text(root / relative)
        if '"PMD' not in text and "," not in relative:
            sources[str((root / relative).resolve())] = relative
            continue
        copy = copies / relative.replace(",", "_")  # PMD's --file-list splits on commas
        copy.parent.mkdir(parents=True, exist_ok=True)
        copy.write_text(without_pmd_suppressions(text), encoding="utf-8")
        sources[str(copy.resolve())] = relative
    return sources


def analyze_java(root: Path, files: List[str], data: dict, errors: List[str], notes: List[str]) -> List[dict]:
    if not shutil.which("java"):
        errors.append("java not found on PATH: PMD skipped (installing PMD would not help until a JDK is on PATH)")
        return []
    if not pmd_executable().exists():
        notes.append("java: PMD is not installed, so only complexity and parameter rules ran. Ask the user, then run: "
                     f"python3 {Path(__file__).resolve()} install-pmd")
        return []
    catalog = data["rules"]["java"]
    results = []
    with tempfile.TemporaryDirectory() as work:
        ruleset = Path(work) / "ruleset.xml"
        ruleset.write_text(pmd_ruleset(data), encoding="utf-8")
        sources = pmd_sources(root, files, Path(work) / "copies")
        listing = Path(work) / "files.txt"
        # PMD splits --file-list entries on commas too; paths relative to the project keep a comma in its folder name out.
        listing.write_text("\n".join(os.path.relpath(path, root) for path in sources), encoding="utf-8")
        report = Path(work) / "pmd.json"
        code, _, err = run_command([str(pmd_executable()), "check", "--no-cache", "--no-progress", "--suppress-marker", "NOSONAR",
                                    "-R", str(ruleset),
                                    "--file-list", str(listing), "-f", "json", "-r", str(report)], cwd=root)
        if code not in PMD_OK_EXIT_CODES or not report.exists():
            errors.append(f"pmd exit {code}: {error_summary(err)}")
            return []
        payload = json.loads(read_text(report) or "{}")
        for item in payload.get("files", []):
            reported = (root / item["filename"]).resolve()
            relative = sources.get(str(reported), relative_to_root(root, str(reported)))
            for violation in item.get("violations", []):
                rule = data["pmd"].get(violation["rule"], [violation["rule"]])[0]
                results.append(finding(relative, violation["beginline"], rule, f"pmd:{violation['rule']}", violation["description"], catalog))
        for problem in payload.get("processingErrors", []):
            errors.append(f"pmd could not parse {problem.get('filename', '?')}: {str(problem.get('message', ''))[:200]}")
    return results


def catalog_for(data: dict, relative: str) -> Dict[str, dict]:
    language = language_of(relative) or ""
