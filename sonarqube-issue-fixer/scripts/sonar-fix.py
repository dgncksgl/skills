def maven_properties(text: str) -> Dict[str, str]:
    block = re.search(r"<properties>(.*?)</properties>", text, re.S)
    if not block:
        return {}
    return {key: value.strip() for key, value in re.findall(r"<([\w.\-]+)>([^<]*)</\1>", block.group(1))}


def resolve_maven(value: str, properties: Dict[str, str], depth: int = 0) -> str:
    match = re.fullmatch(r"\$\{([\w.\-]+)\}", value.strip())
    if match and depth < 5:
        return resolve_maven(properties.get(match.group(1), ""), properties, depth + 1)
    return value.strip()


def normalize_java(value: str) -> str:
    value = value.strip().strip("'\"")
    match = re.match(r"1\.(\d+)$", value)
    if match:
        return match.group(1)
    match = re.match(r"(\d+)", value)
    return match.group(1) if match else "unknown"


def java_version_maven(text: str) -> str:
    properties = maven_properties(text)
    for key in ("maven.compiler.release", "maven.compiler.source", "maven.compiler.target", "java.version",
                "jdk.version", "java.release"):
        if key in properties:
            resolved = resolve_maven(properties[key], properties)
            if resolved:
                return normalize_java(resolved)
    plugin = re.search(r"maven-compiler-plugin.*?<configuration>(.*?)</configuration>", text, re.S)
    if plugin:
        for tag in ("release", "source"):
            match = re.search(rf"<{tag}>([^<]+)</{tag}>", plugin.group(1))
            if match:
                return normalize_java(resolve_maven(match.group(1), properties))
    return "unknown"


def java_version_gradle(text: str) -> str:
    patterns = (
        r"JavaLanguageVersion\.of\(\s*(\d+)\s*\)",
        r"jvmToolchain\(\s*(\d+)\s*\)",
        r"JavaVersion\.VERSION_(\d+(?:_\d+)?)",
        r"(?:source|target)Compatibility\s*=?\s*['\"]?(\d+(?:\.\d+)?)",
        r"JvmTarget\.JVM_(\d+(?:_\d+)?)",
        r"jvmTarget\s*(?:=|\.set\()\s*['\"](\d+(?:\.\d+)?)",
    )
    for pattern in patterns:
        match = re.search(pattern, text)
        if match:
            return normalize_java(match.group(1).replace("_", "."))
    return "unknown"


def python_version(directory: Path) -> str:
    pyproject = read_text(directory / PYPROJECT_FILE)
    spec = toml_value(pyproject, "project", "requires-python") or toml_value(pyproject, "tool.poetry.dependencies", "python")
    if spec:
        return python_lower_bound(spec)
    for line in read_text(directory / ".python-version").splitlines():
        if line.strip() and not line.strip().startswith("#"):
            return major_minor(line.strip())
    for name, pattern in ((SETUP_CFG_FILE, r"python_requires\s*=\s*([^\n]+)"), (SETUP_PY_FILE, r"python_requires\s*=\s*['\"]([^'\"]+)")):
        match = re.search(pattern, read_text(directory / name))
        if match:
            return python_lower_bound(match.group(1))
    match = re.search(r"python-(\d+\.\d+)", read_text(directory / "runtime.txt"))
    return match.group(1) if match else "unknown"


