def tool_note(command: str, directory: Optional[Path] = None) -> str:
    """The command, marked '(missing: x)' when its program is not installed; paths are checked inside the module."""
    head = command.split()[0]
    if "/" in head:
        found = ((directory or Path.cwd()) / head).exists()
    else:
        found = shutil.which(head) is not None
    return command if found else f"{command} (missing: {head})"


