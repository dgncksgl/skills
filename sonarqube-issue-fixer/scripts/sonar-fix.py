class TestLayout(NamedTuple):
    """Sonar's test settings: sonar.tests folders, sonar.test.inclusions patterns, and the sonar.sources folders."""
    prefixes: Tuple[str, ...] = ()
    inclusions: Tuple[str, ...] = ()
    sources: Tuple[str, ...] = ()
    everything_main: bool = False
    module_dirs: Tuple[str, ...] = ()  # Maven/Gradle modules: their sonar.tests / sonar.test.inclusions are module-relative


def under_prefix(relative: str, prefix: str) -> bool:
    prefix = prefix.rstrip("/")
    return prefix in (".", "") or relative == prefix or relative.startswith(prefix + "/")


def test_layout(settings: Dict[str, str], root: Path) -> TestLayout:
    """A project with Sonar settings but no sonar.tests (outside Maven/Gradle, which declare src/test) has no test files
    for Sonar: every file is main code. Without any Sonar settings, file names decide."""
    properties_at_root = (root / SONAR_PROPERTIES_FILE).exists()
    has_sonar_config = properties_at_root or any(key != PROJECT_KEY_SETTING for key in settings)
    # A root sonar-project.properties means the scanner CLI reads it; nested pom/gradle files (examples, tools) do not change that.
    everything_main = (has_sonar_config and not settings.get("sonar.tests")
                       and not has_any(root, MULTI_MODULE_BUILD_FILES + (SETTINGS_GRADLE_FILE, SETTINGS_GRADLE_KTS_FILE))
                       and (properties_at_root or not build_roots(root)))
    prefixes = tuple(sonar_patterns(settings.get("sonar.tests", "")))
    inclusions = tuple(sonar_patterns(settings.get("sonar.test.inclusions", "")))
    module_dirs = tuple(build_roots(root)) if (prefixes or inclusions) and not everything_main else ()
    return TestLayout(prefixes, inclusions, tuple(sonar_patterns(settings.get("sonar.sources", ""))), everything_main, module_dirs)


MAIN, TEST, IGNORED = "main", "test", "ignored"


def folder_of(relative: str) -> str:
    """'/a/b/' for 'a/b/c.py' and '/' for a top-level file, so folder patterns can match whole segments."""
    parts = relative.replace("\\", "/").split("/")[:-1]
    return "/" + "/".join(parts) + "/" if parts else "/"


def in_test_source_set(folder: str) -> bool:
    return any(marker in folder for marker in TEST_SOURCE_SETS) or bool(TEST_SOURCE_SET_PATTERN.search(folder))


def classify_under_tests_setting(relative: str, layout: TestLayout, matches_inclusions: bool) -> str:
    """sonar.tests is set: only files under it can be tests; a folder shared with sonar.sources keeps the rest as main."""
    paths = module_relative_paths(relative, layout.module_dirs)
    under = [prefix for prefix in layout.prefixes if any(under_prefix(path, prefix) for path in paths)]
    if not under:
        return MAIN
    dedicated = any(prefix not in layout.sources for prefix in under)
    if layout.inclusions:
        if matches_inclusions:
            return TEST
        return IGNORED if dedicated else MAIN
    return TEST if dedicated or test_by_name(relative) else MAIN


def classify_by_inclusions(relative: str, matches_inclusions: bool) -> str:
    """No sonar.tests but sonar.test.inclusions: the build's source sets (src/main, src/test) decide the area."""
    folder = folder_of(relative)
    if MAIN_SOURCE_SET_PATTERN.search(folder):
        return MAIN
    if matches_inclusions:
        return TEST
    return IGNORED if in_test_source_set(folder) else MAIN


def classify(relative: str, layout: TestLayout) -> str:
    """How Sonar sees the file: main code, test code, or ignored (a test folder file left out by sonar.test.inclusions)."""
    if layout.everything_main:
        return MAIN
    paths = module_relative_paths(relative, layout.module_dirs)
    matches_inclusions = any(glob_to_regex(item).match(path) for item in layout.inclusions for path in paths)
    if layout.prefixes:
        return classify_under_tests_setting(relative, layout, matches_inclusions)
    if layout.inclusions:
        return classify_by_inclusions(relative, matches_inclusions)
    return TEST if test_by_name(relative) else MAIN


def is_test_path(relative: str, test_prefixes: Sequence[str] = (), test_inclusions: Sequence[str] = (),
                 source_prefixes: Sequence[str] = (), everything_main: bool = False) -> bool:
    layout = TestLayout(tuple(test_prefixes), tuple(test_inclusions), tuple(source_prefixes), everything_main)
    return classify(relative, layout) == TEST


def outside_test_inclusions(relative: str, layout: TestLayout) -> bool:
    return classify(relative, layout) == IGNORED


def test_by_name(relative: str) -> bool:
    parts = relative.replace("\\", "/").split("/")
    folder = folder_of(relative)
    if MAIN_SOURCE_SET_PATTERN.search(folder) and parts[-1].endswith(JVM_SUFFIXES):
        return False
    if in_test_source_set(folder):
        return True
    if any(part in TEST_DIR_NAMES or TEST_PROJECT_DIR_PATTERN.search(part) for part in parts[:-1]):
        return True
    if parts[-1].endswith(".rb") and any(part in RUBY_SPEC_DIR_NAMES for part in parts[:-1]):
        return True
    return bool(TEST_FILE_PATTERN.match(parts[-1]))


def major_minor(version: str) -> str:
    match = re.match(r"\s*(\d+)(?:\.(\d+))?", version)
    if not match:
        return "unknown"
    return f"{match.group(1)}.{match.group(2)}" if match.group(2) is not None else match.group(1)


def clause_lower_bound(clause: str) -> Optional[Tuple[int, int]]:
    """(major, minor) of a lower-bound clause such as '>=3.10' or '^3.11'; None for upper bounds."""
    match = re.match(r"\s*(>=|~=|==|\^|~|>)?\s*(\d+)(?:\.(\d+|\*))?", clause)
    if not match or clause.strip().startswith(("<", "!=")):
        return None
    minor = match.group(3)
    return int(match.group(2)), int(minor) if minor and minor.isdigit() else 0


def python_lower_bound(spec: str) -> str:
    """Lowest Python allowed by a specifier such as '<3.13,>=3.10', '^3.11' or '~2.7 || ^3.6'."""
    candidates: List[Tuple[int, int]] = []
    spec = re.sub(r"([<>=!~^]+)\s+", r"\1", spec)
    for group in re.split(r"\|\|", spec):
        clauses = re.split(r"[,\s]+(?=[<>=!~^\d])", group.strip())
        bounds = [bound for bound in map(clause_lower_bound, clauses) if bound]
        if bounds:
            candidates.append(max(bounds))
    if not candidates:
        return "unknown"
    modern = [item for item in candidates if item[0] >= 3]
    major, minor = min(modern or candidates)
    return f"{major}.{minor}"


def toml_value(text: str, section: str, key: str) -> Optional[str]:
    """String value of key inside [section] of a TOML file (regex based; Python 3.9 has no tomllib)."""
    pattern = re.compile(r"^\[" + re.escape(section) + r"\]\s*$(.*?)(?=^\[|\Z)", re.M | re.S)
    block = pattern.search(text)
    if not block:
        return None
    match = re.search(r"^\s*" + re.escape(key) + r"\s*=\s*[\"']([^\"']*)[\"']", block.group(1), re.M)
    return match.group(1) if match else None


