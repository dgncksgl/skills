def run_analyzers(root: Path, groups: Dict[str, List[str]], data: dict, errors: List[str], notes: List[str]) -> List[dict]:
    """Runs the per-language analyzers side by side; they are separate programs on separate files."""
    jobs = []
    if "python" in groups:
        jobs.append(("python", lambda: analyze_python(root, groups["python"], data, errors, notes)))
    scripts = groups.get("javascript", []) + groups.get("typescript", [])
    if scripts:
        jobs.append(("javascript/typescript", lambda: analyze_javascript(root, scripts, data, errors)))
    if "java" in groups:
        jobs.append(("java", lambda: analyze_java(root, groups["java"], data, errors, notes)))
    lizard_files = [item for language in sorted(LIZARD_LANGUAGES) for item in groups.get(language, [])]
    if lizard_files:
        jobs.append(("lizard", lambda: analyze_lizard(root, lizard_files, data, errors)))

    def guarded(job: Tuple[str, Callable[[], List[dict]]]) -> List[dict]:
        name, run = job
        try:
            return run()
        except (ValueError, KeyError, TypeError, IndexError, OSError, RecursionError) as error:
            errors.append(f"{name} analysis failed on unexpected tool output: {error!r}")
            return []

    with concurrent.futures.ThreadPoolExecutor(max_workers=ANALYZER_WORKERS) as pool:
        batches_of_results = list(pool.map(guarded, jobs))
    return [item for found in batches_of_results for item in found]


STRING_LITERAL_PATTERN = re.compile(r'"(?:[^"\\\n]|\\.)*"|\'(?:[^\'\\\n]|\\.)*\'|`(?:[^`\\\n]|\\.)*`')
NOSONAR_COMMENT_PATTERN = re.compile(r"(#|//|/\*).*\bNOSONAR\b")
PYTHON_SUPPRESSION_PATTERN = re.compile(r"^#\s*(?:NOSONAR(?:\s*\(([^)]*)\))?(?:$|\s)|noqa(?::\s*([^#]+))?(?:$|[\s;:]))")
JAVA_NON_CODE_PATTERN = re.compile(r'/\*.*?\*/|//[^\n]*|"""(?:.|\n)*?"""|"(?:[^"\\\n]|\\.)*"|\'(?:[^\'\\\n]|\\.)*\'', re.DOTALL)
SUPPRESS_WARNINGS_PATTERN = re.compile(r"@(?:java\.lang\.|kotlin\.)?Suppress(?:Warnings)?\s*\(")
SUPPRESSED_RULE_PATTERN = re.compile(r"(?:java|squid|kotlin):S0*(\d+)$")
STRING_VALUE_PATTERN = re.compile(r'"([^"\\\n]*)"')
FOLLOWING_ANNOTATION_PATTERN = re.compile(r"\s*@[\w.]+\s*")
KOTLIN_DECLARATION_PATTERN = re.compile(r"\b(fun|class|object|interface|val|var)\b")
ALL_RULES = "*"
# SonarJava's SuppressWarningFilter: javac warning keys and the rules each one hides.
JAVAC_SUPPRESSED_RULES = {
    "cast": ["S1905"], "deprecation": ["S1874"], "dep-ann": ["S1123"], "divzero": ["S3518"], "empty": ["S1116", "S108"],
    "fallthrough": ["S128"], "finally": ["S1143"], "overrides": ["S1206"], "removal": ["S5738"], "serial": ["S2057"],
    "static": ["S2696", "S2209"], "rawtypes": ["S3740"], "parameternumber": ["S107"], "boxing": ["S2153", "S5411"],
    "hiding": ["S4977"], "javadoc": ["S1176"], "null": ["S2259"], "resource": ["S2093", "S2095"],
    "static-access": ["S2696", "S2209"], "static-method": ["S2325"], "sync-override": ["S3551"],
    "unused": ["S1481", "S1065", "S1854", "S1068", "S3985", "S2326", "S1144", "S1128", "S2583"],
}


def comment_suppresses(line: str, rule: str, language: Optional[str]) -> bool:
    """SonarQube's line suppression: NOSONAR anywhere in a comment (Java, JS, ...); in Python, like SonarPython, a comment
    starting `# NOSONAR` or `# noqa`, optionally limited to rule keys."""
    code = STRING_LITERAL_PATTERN.sub('""', line)
    if language != "python":
        return bool(NOSONAR_COMMENT_PATTERN.search(code))
    comment = code.find("#")
    return comment >= 0 and any(python_marker_suppresses("#" + part, rule) for part in code[comment:].split("#")[1:])


def python_marker_suppresses(comment: str, rule: str) -> bool:
    """One `# NOSONAR[(keys)]` or `# noqa[: keys]` comment: no keys hides every rule, otherwise only the listed ones."""
    match = PYTHON_SUPPRESSION_PATTERN.match(comment)
    if not match:
        return False
    listed = match.group(1) if match.group(1) is not None else match.group(2)
    keys = {key.split(":")[-1] for key in re.split(r"[\s,]+", listed or "") if key}
    return not keys or rule in keys


def matching_close(code: str, start: int, opening: str, closing: str) -> int:
    """Index of the bracket closing the one at start (strings and comments already blanked); -1 if none."""
    depth = 0
    for index in range(start, len(code)):
        if code[index] == opening:
            depth += 1
        elif code[index] == closing:
            depth -= 1
            if depth == 0:
                return index
    return -1


def suppressed_rules(arguments: str, kotlin: bool) -> List[str]:
    """Rule keys an annotation's string arguments hide; "all" and javac keys count only in Java, as in SonarJava."""
    rules = []
    for value in STRING_VALUE_PATTERN.findall(arguments):
        key = SUPPRESSED_RULE_PATTERN.match(value.strip())
        if key:
            rules.append("S" + key.group(1))
        elif not kotlin:
            lowered = value.strip().lower()
            rules.extend([ALL_RULES] if lowered == "all" else JAVAC_SUPPRESSED_RULES.get(lowered, []))
    return rules


def after_annotations(code: str, position: int) -> int:
    """Position after any further annotations (with their arguments) that follow; -1 on unbalanced brackets."""
    while True:
        following = FOLLOWING_ANNOTATION_PATTERN.match(code, position)
        if not following:
            return position
        position = following.end()
        if code.startswith("(", position):
            position = matching_close(code, position, "(", ")") + 1
            if position == 0:
                return -1


def java_declaration_end(code: str, position: int) -> int:
    """`;` of a field or abstract method, or the `}` closing the body; the parameter list is skipped whole,
    since its annotations may hold `{...}` arrays."""
    index = position
    while 0 <= index < len(code):
        if code[index] == "(":
            index = matching_close(code, index, "(", ")")
        elif code[index] in ";{":
            return index if code[index] == ";" else matching_close(code, index, "{", "}")
        if index >= 0:
            index += 1
    return -1


def element_end(code: str, position: int, kotlin: bool) -> int:
    """End of the declaration an annotation ending at position belongs to (later annotations skipped)."""
    position = after_annotations(code, position)
    if position < 0:
        return -1
    if kotlin:
        declaration = KOTLIN_DECLARATION_PATTERN.search(code, position)
        return code.find("\n", declaration.end()) if declaration else -1
    return java_declaration_end(code, position)


def annotation_suppressed_lines(text: str, kotlin: bool) -> Dict[str, Set[int]]:
    """Lines per rule hidden by @SuppressWarnings / @Suppress on a declaration, as SonarQube does (ALL_RULES: every rule)."""
    code = JAVA_NON_CODE_PATTERN.sub(lambda match: re.sub(r"[^\n]", " ", match.group()), text)
    hidden: Dict[str, Set[int]] = {}
    for annotation in SUPPRESS_WARNINGS_PATTERN.finditer(code):
        arguments_end = matching_close(code, annotation.end() - 1, "(", ")")
        rules = suppressed_rules(text[annotation.end():arguments_end], kotlin) if arguments_end >= 0 else []
        on_parameter = code[:annotation.start()].rstrip().endswith(("(", ","))  # covers that parameter only
        end = (arguments_end if on_parameter else element_end(code, arguments_end + 1, kotlin)) if rules else -1
        if end < 0:
            continue
        first = code.count("\n", 0, annotation.start()) + 1
        last = code.count("\n", 0, end) + 1
        for rule in rules:
            hidden.setdefault(rule, set()).update(range(first, last + 1))
    return hidden


def without_suppressed(root: Path, results: List[dict]) -> List[dict]:
    """SonarQube drops issues on a NOSONAR (Python also noqa) line and inside Java/Kotlin suppression annotations."""
    lines_by_file: Dict[str, List[str]] = {}
    java_hidden: Dict[str, Dict[str, Set[int]]] = {}
    kept = []
    for item in results:
        relative = item["file"]
        if relative not in lines_by_file:
            text = read_text(root / relative)
            lines_by_file[relative] = text.split("\n")  # the analyzers count only \n; splitlines() also breaks on \x0c
            language = language_of(relative)
            java_hidden[relative] = annotation_suppressed_lines(text, language == "kotlin") if language in ("java", "kotlin") else {}
        lines = lines_by_file[relative]
        line = lines[item["line"] - 1] if 0 < item["line"] <= len(lines) else ""
        hidden = java_hidden[relative]
        if not comment_suppresses(line, item["rule"], language_of(relative)) and not any(
                item["line"] in hidden.get(key, set()) for key in (item["rule"], ALL_RULES)):
            kept.append(item)
    return kept


def scoped_unique(results: List[dict], data: dict, layout: TestLayout) -> List[dict]:
    """Drops findings whose Sonar scope (Main/Tests) does not match the file, then duplicates."""
    kept = [item for item in results
            if keep_for_scope(item["rule"], catalog_for(data, item["file"]), classify(item["file"], layout) == TEST)]
    kept.sort(key=lambda item: (item["file"], item["line"], item["rule"]))
    unique: List[dict] = []
    seen: Set[Tuple[str, int, str, str]] = set()
    for item in kept:
        key = (item["file"], item["line"], item["rule"], item["message"])
        if key not in seen:
            seen.add(key)
            unique.append(item)
    return unique


