def git_root_state(root: Path) -> Tuple[bool, str, str, int]:
    code, _ = git(root, "rev-parse", "--is-inside-work-tree")
    if code != 0:
        return False, "", "", 0
    code, branch = git(root, "rev-parse", "--abbrev-ref", "HEAD")
    if code != 0:  # no commit yet: rev-parse cannot resolve HEAD, but the branch name exists
        branch = git(root, "symbolic-ref", "-q", "--short", "HEAD")[1]
    status = git_output(root, "status", "--porcelain", "--untracked-files=all", "--", ".")
    dirty = [line for line in status.splitlines() if line.strip() and not line.endswith(".DS_Store")]
    return True, branch.strip(), default_branch(root), len(dirty)


def default_branch(root: Path) -> str:
    code, out = git(root, "symbolic-ref", "-q", "--short", "refs/remotes/origin/HEAD")
    if code == 0 and out.strip():
        return out.strip()
    for name in ("main", "master", "develop"):
        for candidate in (f"origin/{name}", name):
            if git(root, "rev-parse", "--verify", "-q", candidate)[0] == 0:
                return candidate
    return ""


def split_nul(text: str) -> List[str]:
    return [item for item in text.split("\0") if item]


def uncommitted_files(root: Path, has_head: bool) -> Set[str]:
    if has_head:
        tracked = split_nul(git_output(root, "diff", "--name-only", "-z", "--relative", "HEAD"))
    else:
        tracked = split_nul(git_output(root, "ls-files", "-z"))
    untracked = git_output(root, "ls-files", "--others", "--exclude-standard", "-z")
    return set(tracked) | set(split_nul(untracked))


def commit_reference(root: Path, branch: str, base: str) -> Tuple[str, str]:
    """(reference, label) the branch's commits are compared with; ('', '') when there is none."""
    short_base = base.split("/", 1)[1] if base.startswith("origin/") else base
    if branch == "HEAD" and not base:
        print("note=detached HEAD: only uncommitted files are in scope; add --base <branch> to include commits")
        return "", ""
    if branch == "HEAD":
        print(f"note=detached HEAD: compared with {base}; use --base <branch> for another base")
    if base and branch not in (short_base, base):
        return base, f"branch-since-{base}"
    upstream = upstream_of(root)
    if upstream:
        return upstream, "unpushed"
    remote = f"origin/{branch}"
    if git(root, "rev-parse", "--verify", "-q", remote)[0] == 0:
        return remote, f"unpushed-vs-{remote}"
    print(f"note={branch} has no upstream: committed changes are not in scope; add --base <commit or branch> to include them")
    return "", ""


def changed_files(root: Path, branch: str, base: str) -> Tuple[List[str], str]:
    has_head = git(root, "rev-parse", "--verify", "-q", "HEAD")[0] == 0
    files = uncommitted_files(root, has_head)
    origin = [f"uncommitted:{len(files)}"] if files else []
    reference, label = commit_reference(root, branch, base) if has_head else ("", "")
    committed_files = committed_since(root, reference) if reference else set()
    if committed_files:
        origin.append(f"{label}:{len(committed_files)}")
    files |= committed_files
    return sorted(files), "+".join(origin) or "none"


def upstream_of(root: Path) -> str:
    code, out = git(root, "rev-parse", "--abbrev-ref", "--symbolic-full-name", "@{upstream}")
    return out.strip() if code == 0 else ""


def committed_since(root: Path, reference: str) -> Set[str]:
    if git(root, "rev-parse", "--verify", "-q", reference)[0] != 0:
        print(f"note=base {reference} not found (typo, or not fetched?); only uncommitted files are in scope")
        return set()
    code, merge_base = git(root, "merge-base", "HEAD", reference)
    if code != 0 or not merge_base.strip():
        print(f"note=no common commit with {reference}; only uncommitted files are in scope")
        return set()
    committed = git_output(root, "diff", "--name-only", "-z", "--relative", merge_base.strip(), "HEAD")
    return set(split_nul(committed))


def all_files(root: Path, in_git: bool) -> List[str]:
    if in_git:
        return sorted(set(split_nul(git_output(root, "ls-files", "-z", "-co", "--exclude-standard"))))
    collected = []
    for current, directories, names in os.walk(root):
        path = Path(current)
        directories[:] = [name for name in directories if walkable(path, name, root, False)]  # build output is counted later
        collected.extend((path / name).relative_to(root).as_posix() for name in names)
    return sorted(collected)


def expand_paths(root: Path, paths: Sequence[str], in_git: bool) -> List[str]:
    everything = all_files(root, in_git)
    selected: Set[str] = set()
    for raw in paths:
        target = scope_path(root, raw)
        relative = project_relative(root, raw)
        if target.is_file():
            selected.add(relative)
            continue
        prefix = "" if relative == "." else relative + "/"
        matches = [item for item in everything if item.startswith(prefix)]
        if not target.exists() and not matches:
            print(f"note=path not found: {raw}")
        selected.update(matches)
    return sorted(selected)


def is_inside(root: Path, path: Path) -> bool:
    """False for a file (or symlink target) outside the project root."""
    try:
        path.resolve().relative_to(root.resolve())
    except ValueError:
        return False
    return True


class ScopeRules(NamedTuple):
    """sonar.exclusions, sonar.inclusions and sonar.sources, applied to main code only."""
    exclusions: Tuple[str, ...] = ()
    inclusions: Tuple[str, ...] = ()
    sources: Tuple[str, ...] = ()


def sonar_rule_reason(relative: str, rules: ScopeRules, module_dirs: Sequence[str]) -> Optional[str]:
    variants = module_relative_paths(relative, module_dirs)
    sources = [prefix for prefix in rules.sources if prefix not in (".", "")]
    if sources and not any(under_prefix(variant, prefix) for variant in variants for prefix in sources):
        return "outside-sonar.sources"
    if rules.inclusions and not any(glob_to_regex(item).match(variant) for variant in variants for item in rules.inclusions):
        return "outside-sonar.inclusions"
    if any(glob_to_regex(item).match(variant) for variant in variants for item in rules.exclusions):
        return "sonar.exclusions"
    return None


def folder_exclusion_reason(root: Path, relative: str, parts: List[str], in_git: bool,
                            tracked_dirs: AbstractSet[str] = frozenset()) -> Optional[str]:
    """Why a folder on the file's path keeps it out of scope: hidden, dependency or build output, SonarJS default.
    Build-output names are guessed only outside git, or for untracked files in folders git tracks nothing in."""
    if any(part.startswith(".") for part in parts[:-1]):
        return "hidden-dir"
    for index, part in enumerate(parts[:-1]):
        guess = not in_git and "/".join(parts[: index + 1]) not in tracked_dirs
        if skipped_dir(root.joinpath(*parts[:index]), part, root, guess):
            return "dependency-or-build-dir"
    if language_of(relative) in JS_LANGUAGES and SONARJS_DEFAULT_EXCLUDED_DIRS.intersection(parts[:-1]):
        return "sonarjs-default-exclusion"
    return None


def exclusion_reason(root: Path, relative: str, rules: ScopeRules, is_test: bool,
                     module_dirs: Sequence[str] = (), in_git: bool = False,
                     tracked_dirs: AbstractSet[str] = frozenset()) -> Optional[str]:
    path = root / relative
    if language_of(relative) is None:
        return "unsupported-language" if os.path.splitext(relative)[1].lower() in OTHER_SOURCE_EXTENSIONS else "not-source"
    if not path.is_file():
        return "deleted"
    if not is_inside(root, path):
        return "outside-project"
    if relative.endswith(BUILD_SCRIPT_SUFFIX):
        return "build-script"
    parts = relative.split("/")
    folder_reason = folder_exclusion_reason(root, relative, parts, in_git, tracked_dirs)
    if folder_reason:
        return folder_reason
    if GENERATED_NAME_PATTERN.search(parts[-1]) or looks_generated(read_text(path, HEAD_BYTES)):
        return "generated"
    return None if is_test else sonar_rule_reason(relative, rules, module_dirs)


