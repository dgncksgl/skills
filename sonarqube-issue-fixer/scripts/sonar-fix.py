def finding(file: str, line: int, rule: str, tool: str, message: str, catalog: Dict[str, dict]) -> dict:
    meta = catalog.get(rule, {})
    rule_type = meta.get("type", "CODE_SMELL" if rule != SYNTAX_RULE else "BUG")
    action = action_for(rule, rule_type, bool(meta.get("security")))
    return {"file": file, "line": int(line or 1), "rule": rule, "type": rule_type, "action": action,
            "tool": tool, "message": message.strip(), "sonar_way": meta.get("sonar_way", True)}


def action_for(rule: str, rule_type: str, security: bool = False) -> str:
    """security: the rule has a SECURITY impact in Sonar's metadata (vulnerabilities and former hotspots such as S1313)."""
    if rule in REPORT_ONLY_RULES:
        return ACTION_REPORT
    if security or rule_type in ASK_TYPES or rule in DECISION_RULES:
        return ACTION_ASK
    if rule in CHECK_API_RULES:
        return ACTION_CHECK_API
    return ACTION_FIX


def keep_for_scope(rule: str, catalog: Dict[str, dict], is_test: bool) -> bool:
    scope = catalog.get(rule, {}).get("scope", "All")
    if scope == "Main":
        return not is_test
    if scope == "Tests":
        return is_test
    return True


def literals_sonar_skips(tree: ast.AST) -> Set[int]:
    """ids of string constants Sonar's S1192 ignores: docstrings and other bare string statements, and f-string parts."""
    skipped: Set[int] = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Expr) and isinstance(node.value, ast.Constant) and isinstance(node.value.value, str):
            skipped.add(id(node.value))
        elif isinstance(node, ast.JoinedStr):
            skipped.update(id(part) for part in ast.walk(node))
    return skipped


def counts_as_duplicate_candidate(value: str) -> bool:
    if len(value) < DUPLICATE_LITERAL_MIN_LENGTH:
        return False
    return not any(pattern.fullmatch(value) for pattern in (PY_WORD_PATTERN, PY_FORMAT_PATTERN, PY_COLOR_PATTERN))


def string_literal_lines(tree: ast.AST) -> Dict[str, List[int]]:
    skipped = literals_sonar_skips(tree)
    occurrences: Dict[str, List[int]] = {}
    for node in ast.walk(tree):
        if not isinstance(node, ast.Constant) or not isinstance(node.value, str) or id(node) in skipped:
            continue
        if counts_as_duplicate_candidate(node.value):
            occurrences.setdefault(node.value, []).append(node.lineno)
    return occurrences


def python_duplicate_literals(root: Path, relative: str, catalog: Dict[str, dict]) -> Tuple[List[dict], Optional[str]]:
    """Mirror of Sonar's python:S1192 (threshold 3, minimum length 5, docstrings, f-strings and word-like literals skipped)."""
    if Path(relative).name.startswith("test"):
        return [], None
    try:
        tree = ast.parse(read_text(root / relative), filename=relative)
    except (SyntaxError, ValueError, RecursionError, MemoryError) as error:
        return [], f"{relative}: S1192 and S5754 checks skipped, this Python cannot parse it ({error.__class__.__name__})"
    results = []
    for value, lines in string_literal_lines(tree).items():
        if len(lines) >= DUPLICATE_LITERAL_THRESHOLD:
            shown = value if len(value) <= 60 else value[:57] + "..."
            message = (f"Define a constant instead of duplicating this literal {json.dumps(shown, ensure_ascii=False)} {len(lines)} times "
                       f"(lines {', '.join(map(str, sorted(set(lines))))}).")
            results.append(finding(relative, min(lines), "S1192", "sonar-fix:S1192", message, catalog))
    return results, None


@functools.lru_cache(maxsize=None)
def python_target(root: Path) -> Optional[str]:
    version = python_version(root)
    match = re.match(r"3\.(\d+)$", version)
    if not match or int(match.group(1)) < 7:
        return None
    return f"py3{min(int(match.group(1)), RUFF_MAX_PYTHON_MINOR)}"


def relative_to_root(root: Path, path: str, base: Optional[Path] = None) -> str:
    if path.startswith("file:"):
        path = urllib.parse.unquote(urllib.parse.urlparse(path).path)
    candidate = Path(path)
    if not candidate.is_absolute():
        candidate = (base or root) / candidate
    resolved = candidate.resolve()
    try:
        return resolved.relative_to(root).as_posix()
    except ValueError:
        # Case-insensitive file systems: the tool may report the real case of a folder the user typed differently.
        for parent in resolved.parents:
            if parent.exists() and os.path.samefile(parent, root):
                return resolved.relative_to(parent).as_posix()
        return resolved.as_posix()


PYTHON_VERSION_FILES = (PYPROJECT_FILE, SETUP_CFG_FILE, SETUP_PY_FILE, ".python-version", "runtime.txt")


def python_target_for(root: Path, relative: str) -> Optional[str]:
    """ruff target of the nearest folder above the file that declares a Python version (the root as last resort)."""
    folder = (root / relative).parent
    while folder != root and root in folder.parents:
        target = python_target(folder) if has_any(folder, PYTHON_VERSION_FILES) else None
        if target:
            return target
        folder = folder.parent
    return python_target(root)


def ruff_command(data: dict, target: Optional[str]) -> List[str]:
    command = ["uvx", f"ruff@{RUFF_VERSION}", "check", "--isolated", "--no-cache", "--ignore-noqa", "--output-format", "json",
               "--select", ",".join(data["ruff"]), "--config", f"lint.pylint.max-args={PYTHON_PARAMETERS_MAX}",
               "--config", "lint.per-file-ignores={'__init__.py' = ['F401']}"]
    return command + (["--target-version", target] if target else []) + ["--"]


def run_ruff(root: Path, files: List[str], data: dict, errors: List[str]) -> List[dict]:
    results: List[dict] = []
    by_target: Dict[Optional[str], List[str]] = {}
    for relative in files:
        by_target.setdefault(python_target_for(root, relative), []).append(relative)
    for target, group in by_target.items():
        results += run_ruff_group(root, group, data, target, errors)
    return results


def run_ruff_group(root: Path, files: List[str], data: dict, target: Optional[str], errors: List[str]) -> List[dict]:
    catalog = data["rules"]["python"]
    results: List[dict] = []
    for chunk in batches(files):
        code, out, err = run_command(ruff_command(data, target) + chunk, cwd=root)
        if code not in (0, 1):
            errors.append(f"ruff exit {code}: {error_summary(err)}")
            continue
        for item in json.loads(out or "[]"):
            code_name = item.get("code")
            rule = data["ruff"].get(code_name, SYNTAX_RULE if code_name in RUFF_SYNTAX_CODES else code_name)
            results.append(finding(relative_to_root(root, item["filename"]), item["location"]["row"], rule,
                                   f"ruff:{code_name or 'syntax'}", item["message"], catalog))
    return results


def run_complexipy(root: Path, files: List[str], data: dict, errors: List[str]) -> List[dict]:
    catalog = data["rules"]["python"]
    results: List[dict] = []
    for chunk in batches(files):
        with tempfile.TemporaryDirectory() as work:
            report = Path(work) / "complexipy.sarif"
            code, _, err = run_command(["uvx", f"complexipy@{COMPLEXIPY_VERSION}", "--isolated", "-q", "--output-format",
                                        "sarif", "--output", str(report), "--max-complexity-allowed", str(COGNITIVE_COMPLEXITY_MAX),
                                        *[str(root / item) for item in chunk]], cwd=Path(work))
