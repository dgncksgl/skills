def sonar_component_path(component: str, paths: Dict[str, str], project_key: str = "") -> str:
    """File path of a Sonar component key ('' for a project-level issue); project keys may contain ':'."""
    if component in paths:
        return paths[component]
    if not component or component == project_key:
        return ""
    if project_key and component.startswith(project_key + ":"):
        return component[len(project_key) + 1:]
    return component.rsplit(":", 1)[-1] if ":" in component else component


def load_sonar_payload(name: str) -> dict:
    try:
        payload = json.loads(read_text(Path(name)))
    except json.JSONDecodeError as error:
        raise UsageError(f"{name} is not JSON: {error}") from error
    if not isinstance(payload, dict) or not ("issues" in payload or "hotspots" in payload):
        raise UsageError(f"{name} has no 'issues' or 'hotspots' list (expected api/issues/search or api/hotspots/search JSON)")
    return payload


RULE_KEY_LANGUAGES = {"python": "python", "java": "java", "javascript": "javascript", "typescript": "javascript",
                      "js": "javascript", "ts": "javascript"}


def security_engine_type(rule_key: str) -> str:
    """Taint-analysis rules (pythonsecurity:, javasecurity:, jssecurity:, …) are vulnerabilities."""
    return "VULNERABILITY" if rule_key.split(":")[0].endswith("security") else ""


def catalog_for_rule_key(data: dict, rule_key: str) -> Dict[str, dict]:
    """Rule metadata for a Sonar rule key such as 'java:S3776'; other languages use the generic and Java entries."""
    language = RULE_KEY_LANGUAGES.get(rule_key.split(":")[0]) if ":" in rule_key else None
    return data["rules"][language] if language else {**data["rules"]["java"], **data["rules"]["generic"]}


def sonar_issue_finding(issue: dict, forced_type: str, paths: Dict[str, str], data: dict) -> dict:
    path = sonar_component_path(issue.get("component", ""), paths, issue.get("project", "")) or PROJECT_LEVEL_FILE
    rule_key = issue.get("rule") or issue.get("ruleKey") or ""
    rule = rule_key.split(":")[-1] if rule_key else "UNKNOWN"
    line = issue.get("line") or (issue.get("textRange") or {}).get("startLine") or 1
    item = finding(path, line, rule, f"sonarqube:{rule_key}", issue.get("message", ""), catalog_for_rule_key(data, rule_key))
    rule_type = forced_type or issue.get("type", "") or security_engine_type(rule_key)
    has_security_impact = any((impact or {}).get("softwareQuality") == "SECURITY" for impact in issue.get("impacts") or [])
    if rule_type:
        item["type"] = rule_type
    if rule_type or has_security_impact:
        item["action"] = action_for(rule, item["type"], has_security_impact or item["action"] == ACTION_ASK)
    item["sonar_way"] = True
    return item


def command_import(arguments: argparse.Namespace) -> int:
    root = Path(arguments.project).resolve()
    data = load_rules()
    results: List[dict] = []
    for name in arguments.json_files:
        payload = load_sonar_payload(name)
        paths = {item["key"]: item["path"] for item in payload.get("components", []) if item.get("key") and item.get("path")}
        tagged = [(issue, "") for issue in payload.get("issues", [])]
        tagged += [(issue, "SECURITY_HOTSPOT") for issue in payload.get("hotspots", [])]
        results.extend(sonar_issue_finding(issue, forced_type, paths, data) for issue, forced_type in tagged)
    mark_s5754_decisions(root, results)
    results.sort(key=lambda item: (item["file"], item["line"], item["rule"]))
    unresolved = sorted({item["file"] for item in results
                         if item["file"] != PROJECT_LEVEL_FILE and not (root / item["file"]).is_file()})
    if unresolved:
        print(f"note={len(unresolved)} files from the report do not exist under {root} (wrong root or branch?): "
              + ", ".join(unresolved[:5]))
    print_findings(results, write_findings(results, arguments.out))
    return EXIT_OK


# ---------------------------------------------------------------- install-pmd

def file_sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with open(path, "rb") as handle:
        for block in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def download(url: str, target: Path) -> Optional[str]:
    """Downloads url to target; returns an error text, or None on success. A partial file is removed."""
    try:
        with urllib.request.urlopen(url, timeout=COMMAND_TIMEOUT_SECONDS) as response, open(target, "wb") as handle:
            shutil.copyfileobj(response, handle)
    except (OSError, http.client.HTTPException) as error:
        if target.exists():
            target.unlink()
        return f"download failed: {error!r}"
    return None


def unpack_pmd(archive: Path, target: Path) -> Optional[str]:
    """Unpacks into a temporary folder and moves the PMD folder into place only when it is complete."""
    staging = Path(tempfile.mkdtemp(prefix="pmd-unpack-", dir=target))
    try:
        with zipfile.ZipFile(archive) as bundle:
            bundle.extractall(staging)
        unpacked = staging / pmd_home().name
        if not (unpacked / "bin" / "pmd").exists():
            return f"{archive.name} has no {pmd_home().name}/bin/pmd"
        (unpacked / "bin" / "pmd").chmod(0o755)
        if pmd_home().exists():
            shutil.rmtree(pmd_home())  # an earlier, incomplete install without bin/pmd
        unpacked.rename(pmd_home())
    except (zipfile.BadZipFile, OSError) as error:
        return f"could not unpack {archive.name}: {error}"
    finally:
        shutil.rmtree(staging, ignore_errors=True)
    return None


def command_install_pmd(_: argparse.Namespace) -> int:
    if pmd_executable().exists():
        print(f"pmd=cached {pmd_home()}")
        return EXIT_OK
    if not shutil.which("java"):
        print("error=java not found on PATH; PMD needs a JDK, so nothing was downloaded")
        return EXIT_FAILED
    target = cache_dir()
    target.mkdir(parents=True, exist_ok=True)
    archive = target / f"pmd-dist-{PMD_VERSION}-bin.zip"
    print(f"note=downloading PMD {PMD_VERSION} (about 135 MB) from {PMD_URL}", file=sys.stderr)
    problem = download(PMD_URL, archive)
    if not problem:
        digest = file_sha256(archive)
        if digest != PMD_SHA256:
            problem = f"checksum mismatch for {archive.name}: got {digest}, expected {PMD_SHA256}; nothing installed"
        else:
            problem = unpack_pmd(archive, target)
    if archive.exists():
        archive.unlink()
    if problem:
        print(f"error={problem}")
        return EXIT_FAILED
    print(f"pmd=installed {pmd_home()}")
    return EXIT_OK


