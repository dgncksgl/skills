def module_extras(module: Dict[str, str]) -> str:
    """Optional module facts as key=value; a value with spaces is quoted like build and test."""
    pairs = [(key, value) for key, value in module.items() if key in ("node", "typecheck", "test_note")]
    return " ".join(f'{key}="{value}"' if re.search(r"\s", value) else f"{key}={value}" for key, value in pairs)


def print_project_facts(root: Path, in_git: bool, branch: str, base: str, dirty: int) -> Dict[str, str]:
    print(f"root={root}")
    print(f"git={'none' if not in_git else ('dirty:' + str(dirty) if dirty else 'clean')}")
    if in_git:
        print(f"branch={branch} default_branch={base or 'unknown'}")
    for relative, module in discover_modules(root):
        extra = module_extras(module)
        print(f"module={relative} ecosystem={module['ecosystem']} language={module['language']} "
              f"version={module['version']} build=\"{module['build']}\" test=\"{module['test']}\"" + (f" {extra}" if extra else ""))
    settings, sources, credentials = sonar_settings(root)
    if sources:
        print(f"sonar_config={','.join(sources)} project_key={settings.get(PROJECT_KEY_SETTING, 'unknown')} "
              f"host={settings.get('sonar.host.url', 'unknown')} "
              f"exclusions={','.join(sonar_patterns(settings.get('sonar.exclusions', ''))) or 'none'}")
    else:
        print("sonar_config=none")
    for location in credentials:
        print(f"credential={location} (a Sonar token or password is written in the file; never print it)")
    return settings


def scope_candidates(arguments: argparse.Namespace, root: Path, in_git: bool, branch: str, base: str) -> Tuple[str, List[str], str]:
    """Returns (scope name, candidate files, origin); origin is empty when the scope cannot be built."""
    if arguments.paths:
        return "paths", expand_paths(root, arguments.paths, in_git), "paths"
    if arguments.scope == "all":
        return "all", all_files(root, in_git), "all"
    if not in_git:
        return "changed", [], ""
    files, origin = changed_files(root, branch, arguments.base or base)
    return "changed", files, origin


def build_roots(root: Path) -> List[str]:
    """Maven and Gradle module folders, aggregated sub-modules included: Sonar resolves exclusions per module there only."""
    return [relative for path, relative in project_folders(root) if has_any(path, MULTI_MODULE_BUILD_FILES)]


def module_relative_paths(relative: str, module_dirs: Sequence[str]) -> List[str]:
    """The path as Sonar sees it from the root and from each module that contains it (exclusions are module-relative)."""
    return [relative] + [relative[len(module) + 1:] for module in module_dirs if module != "." and relative.startswith(module + "/")]


def scope_settings(settings: Dict[str, str], root: Path) -> Tuple[ScopeRules, TestLayout]:
    """sonar.sources and friends parsed once, for the main-code scope and for the test classification."""
    layout = test_layout(settings, root)
    rules = ScopeRules(tuple(sonar_patterns(settings.get("sonar.exclusions", ""))),
                       tuple(sonar_patterns(settings.get("sonar.inclusions", ""))), layout.sources)
    return rules, layout


def folders_of(files: Iterable[str]) -> Set[str]:
    folders: Set[str] = set()
    for relative in files:
        parts = relative.split("/")[:-1]
        folders.update("/".join(parts[: index + 1]) for index in range(len(parts)))
    return folders


def record_exclusion(excluded: Dict[str, int], generated: Optional[List[str]], relative: str, reason: str) -> None:
    excluded[reason] = excluded.get(reason, 0) + 1
    if reason == "generated" and generated is not None:
        generated.append(relative)


def filter_scope(root: Path, candidates: List[str], settings: Dict[str, str], module_dirs: Optional[Sequence[str]] = None,
                 in_git: bool = False, untracked: AbstractSet[str] = frozenset(),
                 tracked: Optional[Set[str]] = None, generated: Optional[List[str]] = None) -> Tuple[List[str], Dict[str, int], TestLayout]:
    """untracked: files git does not track; build-output folder names are guessed for them (tracked files are source)."""
    rules, layout = scope_settings(settings, root)
    if module_dirs is None:
        module_dirs = build_roots(root) if any(rules) else []
    tracked_dirs = folders_of(tracked if tracked is not None else set(candidates) - set(untracked)) if in_git else set()
    selected: List[str] = []
    excluded: Dict[str, int] = {}
    for relative in candidates:
        if language_of(relative) is not None and outside_test_inclusions(relative, layout):
            excluded["outside-sonar.test.inclusions"] = excluded.get("outside-sonar.test.inclusions", 0) + 1
            continue
        trusted = in_git and relative not in untracked
        reason = exclusion_reason(root, relative, rules, classify(relative, layout) == TEST, module_dirs, trusted, tracked_dirs)
        if reason:
            record_exclusion(excluded, generated, relative, reason)
        else:
            selected.append(relative)
    return selected, excluded, layout


def counts_line(counts: Dict[str, int]) -> str:
    return " ".join(f"{key}:{value}" for key, value in sorted(counts.items())) or "none"


def print_scope(arguments: argparse.Namespace, scope: str, origin: str, selected: List[str], excluded: Dict[str, int],
                layout: TestLayout, generated: Sequence[str] = ()) -> None:
    languages: Dict[str, int] = {}
    for relative in selected:
        language = language_of(relative) or "other"
        languages[language] = languages.get(language, 0) + 1
    tests = sum(1 for relative in selected if classify(relative, layout) == TEST)
    print(f"scope={scope} scope_from={origin} scope_files={len(selected)} test_files={tests}")
    print("languages=" + counts_line(languages))
    print("excluded=" + counts_line({key: value for key, value in excluded.items() if key != "not-source"}))
    if generated:
        shown = ",".join(generated[:GENERATED_SHOWN_MAX])
        print(f"generated_files={shown}" + (f" (+{len(generated) - GENERATED_SHOWN_MAX} more)" if len(generated) > GENERATED_SHOWN_MAX else ""))
    if arguments.out:
        Path(arguments.out).parent.mkdir(parents=True, exist_ok=True)
        Path(arguments.out).write_text("".join(item + "\n" for item in selected), encoding="utf-8")
        print(f"scope_list={Path(arguments.out).resolve()}")
    else:
        for relative in selected:
            print(f"file={relative}")
    print("tools=" + " ".join(f"{name}:{'yes' if shutil.which(name) else 'no'}" for name in ("uvx", "node", "npm", "java"))
          + f" pmd:{'cached' if pmd_executable().exists() else 'missing'}")


def command_inspect(arguments: argparse.Namespace) -> int:
    root = Path(arguments.project).resolve()
    if not root.is_dir():
        raise UsageError(f"not a directory: {arguments.project}")
    in_git, branch, base, dirty = git_root_state(root)
    settings = print_project_facts(root, in_git, branch, base, dirty)
    scope, candidates, origin = scope_candidates(arguments, root, in_git, branch, base)
    if not origin:
        print("error=--scope changed needs git; ask the user, then use --scope all or --paths")
        return EXIT_FAILED
    untracked = set(split_nul(git_output(root, "ls-files", "--others", "--exclude-standard", "-z"))) if in_git else set()
    tracked = set(split_nul(git_output(root, "ls-files", "-z"))) if in_git else None
    generated: List[str] = []
    selected, excluded, layout = filter_scope(root, candidates, settings, None, in_git, untracked, tracked, generated)
    print_scope(arguments, scope, origin, selected, excluded, layout, generated)
    return EXIT_OK


