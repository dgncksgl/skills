def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(prog="sonar-fix.py", description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    commands = parser.add_subparsers(dest="command", required=True)
    inspect = commands.add_parser("inspect", help="project facts and scan scope")
    inspect.add_argument("project", nargs="?", default=".")
    inspect.add_argument("--scope", choices=("changed", "all"), default="changed")
    inspect.add_argument("--base", help="branch to compare against for --scope changed (default: the repository default branch)")
    inspect.add_argument("--paths", nargs="+", help="explicit files or directories (overrides --scope)")
    inspect.add_argument("--out", help="write the scope file list here")
    analyze = commands.add_parser("analyze", help="run local analyzers on the scope")
    analyze.add_argument("project", nargs="?", default=".")
    analyze.add_argument("--files-from", help="file with one project-relative path per line (inspect --out)")
    analyze.add_argument("--out", help="write findings JSON here")
    analyze.add_argument("files", nargs="*")
    importer = commands.add_parser("import", help="normalize SonarQube Web API JSON (api/issues/search, api/hotspots/search)")
    importer.add_argument("project", help="project root the Sonar paths are relative to")
    importer.add_argument("json_files", nargs="+")
    importer.add_argument("--out", help="write findings JSON here")
    commands.add_parser("install-pmd", help="download the pinned PMD release into the cache")
    return parser


def main(argv: Optional[Sequence[str]] = None) -> int:
    parser = build_parser()
    arguments = parser.parse_args(argv)  # argparse exits with 2 (EXIT_USAGE) on bad arguments and 0 after --help
    handlers = {"inspect": command_inspect, "analyze": command_analyze, "import": command_import,
                "install-pmd": command_install_pmd}
    try:
        return handlers[arguments.command](arguments)
    except UsageError as error:
        print(f"usage error: {error}", file=sys.stderr)
        return EXIT_USAGE
    except GitFailure as error:
        print(f"error={error}; the scope cannot be trusted, so nothing was listed")
        return EXIT_FAILED


if __name__ == "__main__":
    sys.exit(main())
