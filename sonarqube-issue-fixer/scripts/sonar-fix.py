def scope_path(root: Path, item: str) -> Path:
    """The file an argument names; an absolute path keeps its last part, so a symlink to outside stays visible."""
    given = Path(item)
    if given.is_absolute():
        return Path(os.path.realpath(given.parent)) / given.name
    return Path(os.path.normpath(root / item))


def project_relative(root: Path, raw: str) -> str:
    """Root-relative path of a command-line path; a path outside the project is a usage error."""
    try:
        return scope_path(root, raw).relative_to(root).as_posix()
    except ValueError as error:
        raise UsageError(f"path outside the project: {raw}") from error


def read_scope(arguments: argparse.Namespace, root: Path) -> List[str]:
    items: List[str] = []
    if arguments.files_from:
        items.extend(line.strip() for line in read_text(Path(arguments.files_from)).splitlines() if line.strip())
    items.extend(arguments.files or [])
    resolved = []
    for item in items:
        path = scope_path(root, item)
        if not path.is_file():
            print(f"note=file not found: {item} (paths are relative to the project root)")
            continue
        try:
            relative = project_relative(root, item)
        except UsageError:
            print(f"note=skipped {item}: it is outside the project")
            continue
        if is_inside(root, path):
            resolved.append(relative)
        else:
            print(f"note=skipped {relative}: it links to a file outside the project")
    return sorted(set(resolved))


