def aggregates_children(directory: Path, ecosystem: str) -> bool:
    if ecosystem == "maven":
        return "<modules>" in read_text(directory / POM_FILE)
    if ecosystem == "gradle":
        return has_any(directory, (SETTINGS_GRADLE_FILE, SETTINGS_GRADLE_KTS_FILE))
    if ecosystem in NODE_ECOSYSTEMS:
        return "workspaces" in package_json(directory) or (directory / "pnpm-workspace.yaml").exists()
    if ecosystem == "python":
        return "[tool.uv.workspace]" in read_text(directory / PYPROJECT_FILE)
    if ecosystem == "go":
        return (directory / "go.work").exists()
    if ecosystem == "dotnet":
        return any(directory.glob("*.sln"))
    if ecosystem == "cargo":
        return "[workspace]" in read_text(directory / CARGO_FILE)
    return False


def is_build_output_dir(parent: Path, name: str, root: Path) -> bool:
    if name not in BUILD_OUTPUT_DIR_NAMES:
        return False
    return parent == root or has_any(parent, BUILD_FILE_NAMES) or any(parent.glob("*.csproj"))


@functools.lru_cache(maxsize=None)
def skipped_dir(parent: Path, name: str, root: Path, guess_build_output: bool = True) -> bool:
    """Dependency, tool, virtualenv or build-output folder whose files are never first-party source.
    Under git, .gitignore already drops build output, so names like bin/ or dist/ are only guessed outside git."""
    folder = parent / name
    return (name in EXCLUDED_DIR_NAMES or (folder / VENV_MARKER).exists() or (folder / "conda-meta").is_dir()
            or (guess_build_output and is_build_output_dir(parent, name, root)))


def walkable(path: Path, name: str, root: Path, guess_build_output: bool = True) -> bool:
    return not name.startswith(".") and not skipped_dir(path, name, root, guess_build_output)


def ecosystem_family(ecosystem: str) -> str:
    return "node" if ecosystem in NODE_ECOSYSTEMS else ecosystem


def covered_by_aggregator(relative: str, ecosystem: str, aggregators: List[Tuple[str, str]]) -> bool:
    return any(ecosystem_family(kind) == ecosystem_family(ecosystem) and parent != relative and (parent == "." or relative.startswith(parent + "/"))
               for parent, kind in aggregators)


@functools.lru_cache(maxsize=None)
def project_folders(root: Path) -> Tuple[Tuple[Path, str], ...]:
    """(folder, root-relative path) for each folder that may hold a module, up to MAX_WALK_DEPTH levels deep (walked once)."""
    return tuple(walk_project_folders(root))


def walk_project_folders(root: Path) -> Iterable[Tuple[Path, str]]:
    for current, directories, _ in os.walk(root):
        path = Path(current)
        relative = path.relative_to(root).as_posix()
        depth = 0 if relative == "." else relative.count("/") + 1
        directories[:] = sorted(name for name in directories if walkable(path, name, root)) if depth < MAX_WALK_DEPTH else []
        yield path, relative


def discover_modules(root: Path) -> List[Tuple[str, dict]]:
    result: List[Tuple[str, dict]] = []
    aggregators: List[Tuple[str, str]] = []
    for path, relative in project_folders(root):
        add_modules(path, relative, result, aggregators)
    if not any(module["ecosystem"] == "python" for _, module in result) and any(any(path.glob("*.py")) for path, _ in project_folders(root)):
        result.append((".", python_module(root)))  # plain scripts with no packaging file still have tests to run
    return result


def add_modules(path: Path, relative: str, result: List[Tuple[str, dict]], aggregators: List[Tuple[str, str]]) -> None:
    """Adds the modules found in path unless a parent module of the same ecosystem already aggregates them."""
    for module in modules_in(path):
        if covered_by_aggregator(relative, module["ecosystem"], aggregators):
            continue
        result.append((relative, module))
        if aggregates_children(path, module["ecosystem"]):
            aggregators.append((relative, module["ecosystem"]))


# ---------------------------------------------------------------- Sonar configuration

SonarEntries = List[Tuple[str, str, str]]


def logical_lines(text: str) -> List[Tuple[int, str]]:
    """Joins backslash-continued lines of a .properties file; each entry keeps the number of its first line."""
    joined: List[Tuple[int, str]] = []
    pending: Optional[Tuple[int, str]] = None
    for number, raw in enumerate(text.splitlines(), 1):
        if not pending and raw.lstrip().startswith(("#", "!")):
            joined.append((number, raw))
            continue
        start, prefix = pending if pending else (number, "")
        line = prefix + (raw.lstrip() if pending else raw)
        if (len(line) - len(line.rstrip("\\"))) % 2 == 1:  # an odd count: the last backslash continues the line
            pending = (start, line[:-1])
            continue
        pending = None
        joined.append((start, line))
    if pending:
        joined.append(pending)
    return joined


def properties_entries(root: Path) -> SonarEntries:
    """(key, value, location) for each sonar.* entry of sonar-project.properties."""
    entries = []
    for number, line in logical_lines(read_text(root / SONAR_PROPERTIES_FILE)):
        match = re.match(r"\s*(sonar\.[\w.]+)\s*[=:]\s*(.*)$", line)
        if match:
            entries.append((match.group(1), match.group(2), f"{SONAR_PROPERTIES_FILE}:{number}"))
    return entries


def without_xml_comments(text: str) -> str:
    """Blanks <!-- ... --> blocks and <profiles> (settings that apply only when a profile is active), keeping line breaks."""
    keep_lines = lambda match: "\n" * match.group(0).count("\n")
    text = re.sub(r"<!--.*?-->", keep_lines, text, flags=re.S)
    return re.sub(r"<profiles>.*?</profiles>", keep_lines, text, flags=re.S)


def pom_entries(pom: str) -> SonarEntries:
    """(key, value, location) for each <sonar.*> property of pom.xml, values may span lines."""
    pom = without_xml_comments(pom)
    entries = []
    for match in re.finditer(r"<(sonar\.[\w.]+)>([^<]*)</\1>", pom):
        line = pom.count("\n", 0, match.start(2)) + 1 + leading_newlines(match.group(2))
        entries.append((match.group(1), match.group(2), f"{POM_FILE}:{line}"))
    return entries


def gradle_entries(root: Path, name: str) -> SonarEntries:
    text = read_text(root / name)
    found = re.findall(r"property\s*\(?\s*[\"'](sonar\.[\w.]+)[\"']\s*,\s*[\"']([^\"']*)[\"']", text)
    return [(key, value, name) for key, value in found]


def sonar_settings(root: Path) -> Tuple[Dict[str, str], List[str], List[str]]:
    """Returns (settings, source files, credential locations) from sonar-project.properties, pom.xml and Gradle."""
    pom = read_text(root / POM_FILE)
    sources_and_entries = [(SONAR_PROPERTIES_FILE, properties_entries(root)), (POM_FILE, pom_entries(pom))]
    sources_and_entries += [(name, gradle_entries(root, name)) for name in (GRADLE_FILE, GRADLE_KTS_FILE)]
    settings: Dict[str, str] = {}
    sources: List[str] = []
    credentials: List[str] = []
    for source, entries in sources_and_entries:
        if entries or (source == SONAR_PROPERTIES_FILE and (root / source).exists()):
            sources.append(source)
        for key, value, location in entries:
            settings.setdefault(key, value.strip())
            if is_credential(key, value):
                credentials.append(location)
    default_key = maven_project_key(pom) if pom and PROJECT_KEY_SETTING not in settings else None
    if default_key:
        settings[PROJECT_KEY_SETTING] = default_key
    return settings, sources, credentials


def maven_project_key(pom: str) -> Optional[str]:
    """Sonar's default key for a Maven project: groupId:artifactId (groupId inherited from <parent> when absent)."""
    pom = without_xml_comments(pom)
    body = re.sub(r"<(parent|dependencies|dependencyManagement|build|profiles|plugins)>.*?</\1>", "", pom, flags=re.S)
    artifact = re.search(r"<artifactId>([^<]+)</artifactId>", body)
    group = re.search(r"<groupId>([^<]+)</groupId>", body)
    if not group:
        parent = re.search(r"<parent>(.*?)</parent>", pom, re.S)
        group = re.search(r"<groupId>([^<]+)</groupId>", parent.group(1)) if parent else None
    if not artifact or not group:
        return None
    return f"{group.group(1).strip()}:{artifact.group(1).strip()}"


def leading_newlines(value: str) -> int:
    """Lines between an opening tag and the first non-blank character of its value."""
    return value[: len(value) - len(value.lstrip())].count("\n")


def is_credential(key: str, value: str) -> bool:
    value = value.strip()
    return key in ("sonar.login", "sonar.token", "sonar.password") and bool(value) and not value.startswith("${")


def sonar_patterns(value: str) -> List[str]:
    patterns = []
    for item in re.split(r"[,\n]", value or ""):
        item = item.strip()
        for base_dir in MAVEN_BASEDIR_PROPERTIES:
            item = "." if item == base_dir else item.replace(base_dir + "/", "")
        if item and "${" not in item:
            patterns.append(item[2:] if item.startswith("./") else item)
    return patterns


@functools.lru_cache(maxsize=None)
def glob_to_regex(pattern: str) -> re.Pattern:
    result = ""
    index = 0
    while index < len(pattern):
        if pattern.startswith("**/", index):
            result += r"(?:.*/)?"
            index += 3
        elif pattern.startswith("**", index):
            result += r".*"
            index += 2
        elif pattern[index] == "*":
            result += r"[^/]*"
            index += 1
        elif pattern[index] == "?":
            result += r"[^/]"
            index += 1
        else:
            result += re.escape(pattern[index])
            index += 1
    return re.compile(result + r"$")


