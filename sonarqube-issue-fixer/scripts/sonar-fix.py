def read_text(path: Path, limit: Optional[int] = None) -> str:
    try:
        with open(path, "r", encoding="utf-8", errors="replace") as handle:
            return handle.read(limit) if limit else handle.read()
    except OSError:
        return ""


def run_command(command: Sequence[str], cwd: Optional[Path] = None, timeout: int = COMMAND_TIMEOUT_SECONDS) -> Tuple[int, str, str]:
    try:
        completed = subprocess.run(list(command), cwd=str(cwd) if cwd else None, capture_output=True, text=True,
                                   timeout=timeout, check=False)
    except FileNotFoundError:
        return 127, "", f"command not found: {command[0]}"
    except OSError as error:
        hint = " (argument list too long)" if error.errno == errno.E2BIG else ""
        return 126, "", f"could not start {command[0]}: {error.strerror or error}{hint}"
    except subprocess.TimeoutExpired:
        return 124, "", f"timed out after {timeout}s: {' '.join(command[:3])}"
    return completed.returncode, completed.stdout, completed.stderr


def error_summary(stderr: str) -> str:
    """The first lines of a tool's stderr that are not [WARN] blocks, cut to a readable length."""
    kept: List[str] = []
    in_warning = False
    for line in stderr.splitlines():
        if line.startswith("[WARN]"):
            in_warning = True
            continue
        if in_warning and line[:1] in (" ", "\t"):
            continue
        in_warning = False
        if line.strip():
            kept.append(line.strip())
    return " ".join(kept)[:ERROR_SUMMARY_LENGTH]


