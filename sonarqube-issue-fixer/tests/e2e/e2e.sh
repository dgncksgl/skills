#!/usr/bin/env bash
# End-to-end checks for sonarqube-issue-fixer/scripts/sonar-fix.py. Usage: PY=python3 bash e2e.sh
set -uo pipefail
PY=${PY:-python3}
HERE=$(cd "$(dirname "$0")" && pwd)
FIX=$HERE/fixtures
S=${SONARFIX_SCRIPT:-$(cd "$HERE/../../scripts" && pwd)/sonar-fix.py}
E=${WORK:-${TMPDIR:-/tmp}/sonarqube-issue-fixer-e2e}
rm -rf "$E"; mkdir -p "$E"
PASS=0; FAIL=0
check() { local name=$1; shift; if eval "$@" >/dev/null 2>&1; then PASS=$((PASS+1)); else FAIL=$((FAIL+1)); echo "FAIL: $name :: $*"; fi; }
G() { git -c user.email=t@t -c user.name=t "$@"; }
newrepo() { mkdir -p "$1" && (cd "$1" && git init -q -b main . ); }
rules() { $PY -c "import json,sys;print(' '.join(sorted({f['rule'] for f in json.load(open(sys.argv[1])) if (len(sys.argv)<3 or f['file'].startswith(sys.argv[2]))})))" "$@"; }

# 1 changed-uncommitted
R=$E/c1; newrepo $R; cd $R; printf 'a=1\n' > a.py; printf 'b=1\n' > b.py; printf 'c=1\n' > c.py; G add -A; G commit -qm init
printf 'a=2\n' > a.py; printf 'd=1\n' > d.py
O=$($PY $S inspect . 2>&1)
check c1-files "grep -q 'scope_files=2' <<<\"\$O\""
check c1-from "grep -q 'scope_from=uncommitted:2' <<<\"\$O\""
check c1-list "grep -q '^file=a.py' <<<\"\$O\" && grep -q '^file=d.py' <<<\"\$O\""

# 2 changed-branch (all committed on a feature branch)
R=$E/c2; newrepo $R; cd $R; printf 'a=1\n' > a.py; G add -A; G commit -qm init
G switch -qc feat; printf 'b=1\n' > b.py; printf 'c=1\n' > c.py; G add -A; G commit -qm work
O=$($PY $S inspect . 2>&1)
check c2-from "grep -q 'scope_from=branch-since-main:2' <<<\"\$O\""
check c2-files "grep -q 'scope_files=2' <<<\"\$O\""
check c2-base "$PY $S inspect . --base feat | grep -q 'scope_files=0'"

# 3 clean main
cd $E/c1; G add -A; G commit -qm more
check c3-empty "$PY $S inspect . | grep -q 'scope_files=0'"

# 4 no git
mkdir -p $E/nogit; printf 'x=1\n' > $E/nogit/x.py
O=$($PY $S inspect $E/nogit 2>&1); RC=$?
check c4-exit1 "[ $RC -eq 1 ]"
check c4-error "grep -q '^error=--scope changed needs git' <<<\"\$O\""
check c4-all "$PY $S inspect $E/nogit --scope all | grep -q 'scope_files=1'"

# 5 sonar exclusions + credential
R=$E/c5; newrepo $R; cd $R; mkdir -p src/main/java/a/model src/test/java/a/model
printf 'sonar.projectKey=com.acme:svc\nsonar.exclusions=**/model/**\nsonar.token=abcSECRET123\nsonar.tests=src/test\n' > sonar-project.properties
echo 'class M{}' > src/main/java/a/model/M.java; echo 'class S{}' > src/main/java/a/S.java; echo 'class MTest{}' > src/test/java/a/model/MTest.java
O=$($PY $S inspect . --scope all 2>&1)
check c5-excl "grep -q 'sonar.exclusions:1' <<<\"\$O\""
check c5-test-kept "grep -q '^file=src/test/java/a/model/MTest.java' <<<\"\$O\""
check c5-main-dropped "! grep -q '^file=src/main/java/a/model/M.java' <<<\"\$O\""
check c5-cred "grep -q '^credential=sonar-project.properties:3' <<<\"\$O\""
check c5-no-secret "! grep -q 'abcSECRET123' <<<\"\$O\""
check c5-key "grep -q 'project_key=com.acme:svc' <<<\"\$O\""
sed -i '' '/^sonar.tests=/d' sonar-project.properties
O=$($PY $S inspect . --scope all 2>&1)
check c5b-no-tests-setting "grep -q 'sonar.exclusions:2' <<<\"\$O\" && grep -q 'test_files=0' <<<\"\$O\""

# 6 generated, venv, minified, d.ts, gradle kts
R=$E/c6; newrepo $R; cd $R; mkdir -p env/lib web types
printf '// Code generated by protoc-gen-go. DO NOT EDIT.\npackage x\n' > x.pb2.go; printf '# Code generated by tool. DO NOT EDIT.\nx=1\n' > gen.py
touch env/pyvenv.cfg; echo 'x=1' > env/lib/v.py; echo 'var a=1' > web/a.min.js; echo 'export declare const a: number;' > types/a.d.ts
echo 'plugins {}' > build.gradle.kts; echo 'y=1' > real.py
O=$($PY $S inspect . --scope all 2>&1)
check c6-only-real "grep -q 'scope_files=1' <<<\"\$O\" && grep -q '^file=real.py' <<<\"\$O\""

# 7 python seeded (Phase 2 project)
R=$E/p1; cp -R $FIX/p1 $R; cd $R
$PY $S inspect . --scope all --out $E/p1.scope >/dev/null; $PY $S analyze . --files-from $E/p1.scope --out $E/p1.json > $E/p1.out 2>&1; RC=$?
check c7-exit "[ $RC -eq 0 ]"
check c7-main-rules "[ \"\$(rules $E/p1.json app/)\" = 'S1066 S107 S1128 S1172 S1192 S1481 S2068 S2208 S3776 S4790 S5754' ]"
check c7-test-rules "[ \"\$(rules $E/p1.json tests/)\" = 'S1481' ]"
check c7-s1172-per-param "[ \$(grep -c ' S1172 ' $E/p1.out) -eq 12 ]"

# 8 js seeded
R=$E/p2; cp -R $FIX/p2 $R; cd $R
$PY $S inspect . --scope all --out $E/p2.scope >/dev/null; $PY $S analyze . --files-from $E/p2.scope --out $E/p2.json > $E/p2.out 2>&1
check c8-rules "[ \"\$(rules $E/p2.json src/)\" = 'S1481 S1854 S3358 S3776 SYNTAX' ]"
check c8-test-none "[ -z \"\$(rules $E/p2.json test/)\" ]"

# 9 lizard languages
R=$E/c9; newrepo $R; cd $R
printf 'fun k(a:Int,b:Int,c:Int,d:Int,e:Int,f:Int,g:Int,h:Int): Int { return a }\n' > K.kt
printf 'package m\nfunc G(a, b, c, d, e, f, g, h int) int { return a }\n' > g.go
printf 'class C { int M(int a,int b,int c,int d,int e,int f,int g,int h) { return a; } }\n' > C.cs
printf 'func s(a:Int,b:Int,c:Int,d:Int,e:Int,f:Int,g:Int,h:Int) -> Int { return a }\n' > S.swift
O=$($PY $S analyze . K.kt g.go C.cs S.swift 2>&1)
for f in K.kt g.go C.cs S.swift; do check "c9-s107-$f" "grep -q '^finding=$f:[0-9]* S107' <<<\"\$O\""; done
for l in kotlin go csharp swift; do check "c9-review-$l" "grep -q '^review=$l' <<<\"\$O\""; done

# 10 import
cd $FIX
check c10-import "$PY $S import $FIX/p3 $FIX/sonar-issues.json $FIX/sonar-hotspots.json --out $E/imp.json | grep -q 'findings=4 fix=1 check-api=0 ask=2 report=1'"
check c10-bad "$PY $S import $FIX/p3 $FIX/bad.json; [ \$? -eq 2 ]"

# 11 offline eslint install
R=$E/c11; newrepo $R; cd $R; echo 'const a = 1;' > a.js
O=$(XDG_CACHE_HOME=$E/emptycache npm_config_registry=http://127.0.0.1:9 npm_config_fetch_retries=0 npm_config_fetch_timeout=2000 $PY $S analyze . a.js 2>&1); RC=$?
check c11-exit1 "[ $RC -eq 1 ]"
check c11-error "grep -q '^error=npm install of the ESLint toolchain failed' <<<\"\$O\""

# 12 newer syntax under python 3.9
R=$E/c12; newrepo $R; cd $R; printf 'type Alias = list[int]\nimport os\n' > n.py
O=$(/usr/bin/python3 $S analyze . n.py 2>&1); RC=$?
check c12-exit0 "[ $RC -eq 0 ]"
check c12-note "grep -q 'S1192 and S5754 checks skipped' <<<\"\$O\""
check c12-ruff-ran "grep -q '^finding=n.py:2 S1128' <<<\"\$O\""

# 13 paths outside
cd $E/c1; $PY $S inspect . --paths ../c2 >/dev/null 2>&1; RC=$?
check c13-usage "[ $RC -eq 2 ]"

# 14 no side effects
cd $E/p1; G add -A >/dev/null 2>&1; G commit -qm snapshot >/dev/null 2>&1
$PY $S analyze . --files-from $E/p1.scope --out $E/p1b.json >/dev/null 2>&1
check c14-clean "[ -z \"\$(git status --porcelain --ignored)\" ]"

# 15 review: Kotlin test file keeps no Main-scope rule
R=$E/c15; newrepo $R; cd $R; mkdir -p src/test/kotlin/a src/main/kotlin/a
printf 'class FooTest {\n fun k(a:Int,b:Int,c:Int,d:Int,e:Int,f:Int,g:Int,h:Int): Int { return a }\n}\n' > src/test/kotlin/a/FooTest.kt
printf 'fun k(a:Int,b:Int,c:Int,d:Int,e:Int,f:Int,g:Int,h:Int): Int { return a }\n' > src/main/kotlin/a/Main.kt
O=$($PY $S analyze . src/test/kotlin/a/FooTest.kt src/main/kotlin/a/Main.kt 2>&1)
check c15-test-dropped "! grep -q '^finding=src/test/kotlin/a/FooTest.kt' <<<\"\$O\""
check c15-main-kept "grep -q '^finding=src/main/kotlin/a/Main.kt:1 S107' <<<\"\$O\""

# 16 review: unpushed commits on the default branch are in scope
rm -rf $E/c16-remote $E/c16; git init -q --bare -b main $E/c16-remote; git clone -q $E/c16-remote $E/c16 2>/dev/null; cd $E/c16
printf 'a=1\n' > a.py; G add -A; G commit -qm base; git push -q origin main 2>/dev/null
printf 'b=1\n' > b.py; G add -A; G commit -qm local
O=$($PY $S inspect . 2>&1)
check c16-unpushed "grep -q 'scope_from=unpushed:1' <<<\"\$O\" && grep -q '^file=b.py' <<<\"\$O\""

# 17 review: Python syntax error is SYNTAX
R=$E/c17; newrepo $R; cd $R; printf 'def f(:\n    pass\n' > bad.py
O=$($PY $S analyze . bad.py 2>&1)
check c17-syntax "grep -q '^finding=bad.py:1 SYNTAX' <<<\"\$O\""

# 18 review: large scope is analyzed in batches, no crash
R=$E/c18; newrepo $R; cd $R; mkdir -p pkg_with_a_rather_long_directory_name_to_inflate_the_argument_list
for i in $(seq 1 1200); do printf 'import os\n' > pkg_with_a_rather_long_directory_name_to_inflate_the_argument_list/module_number_$i.py; done
ls pkg_*/*.py > $E/c18.scope
O=$($PY $S analyze . --files-from $E/c18.scope 2>&1); RC=$?
check c18-exit0 "[ $RC -eq 0 ]"
check c18-all-found "grep -q '^findings=1200 ' <<<\"\$O\""

# 19 review: multi-line pom exclusions are applied and printed on one line
R=$E/c19; newrepo $R; cd $R; mkdir -p src/main/java/a/model src/main/java/a/svc
printf '<project><groupId>g</groupId><artifactId>a</artifactId><properties>\n<sonar.exclusions>\n  **/model/**,\n  **/dto/**\n</sonar.exclusions>\n</properties></project>\n' > pom.xml
echo 'class M{}' > src/main/java/a/model/M.java; echo 'class S{}' > src/main/java/a/svc/S.java
O=$($PY $S inspect . --scope all 2>&1)
check c19-applied "grep -q 'sonar.exclusions:1' <<<\"\$O\" && ! grep -q '^file=src/main/java/a/model/M.java' <<<\"\$O\""
check c19-one-line "grep -q 'exclusions=\*\*/model/\*\*,\*\*/dto/\*\*$' <<<\"\$O\""

# 20 review r1: symlink pointing outside the project does not abort analyze
R=$E/c20; newrepo $R; mkdir -p $E/c20-outside; printf 'import os\n' > $E/c20-outside/shared.py; cd $R
printf 'import sys\n' > own.py; ln -s ../c20-outside/shared.py link.py; G add -A; G commit -qm init
O=$($PY $S inspect . --scope all --out $E/c20.scope 2>&1)
check c20-excluded "grep -q 'outside-project:1' <<<\"\$O\""
O=$($PY $S analyze . own.py link.py 2>&1); RC=$?
check c20-no-abort "[ $RC -eq 0 ] && grep -q '^finding=own.py:1 S1128' <<<\"\$O\""

# 21 review r1: a --paths entry that does not exist is reported
cd $E/c1; O=$($PY $S inspect . --paths a.py servcie.py 2>&1)
check c21-missing "grep -q '^note=path not found: servcie.py' <<<\"\$O\" && grep -q 'scope_files=1' <<<\"\$O\""

# 22 review r2: project eslint-disable comments neither hide nor invent findings
R=$E/c22; newrepo $R; cd $R; mkdir -p src
printf '// eslint-disable-next-line react-hooks/exhaustive-deps\nexport const a = 1;\nexport function f() { const unused = 1; // eslint-disable-line sonarjs/no-unused-vars\n  return 2; }\n' > src/y.js
O=$($PY $S analyze . src/y.js 2>&1)
check c22-no-bogus "! grep -q 'react-hooks' <<<\"\$O\""
check c22-not-hidden "grep -q '^finding=src/y.js:3 S1481' <<<\"\$O\""

# 23 review r2: nested module on a newer Python gets no false SYNTAX finding
R=$E/c23; newrepo $R; cd $R; mkdir -p backend
printf '[project]\nname="r"\nversion="0"\nrequires-python=">=3.9"\n' > pyproject.toml
printf '[project]\nname="b"\nversion="0"\nrequires-python=">=3.12"\n' > backend/pyproject.toml
printf 'type X = int\n\ndef f[T](a: T) -> T:\n    return a\n' > backend/m.py
O=$($PY $S analyze . backend/m.py 2>&1)
check c23-no-syntax "! grep -q ' SYNTAX ' <<<\"\$O\""

# 24 review r2: stale local main is not used when origin/main exists
rm -rf $E/c24-remote $E/c24; git init -q --bare -b main $E/c24-remote; git clone -q $E/c24-remote $E/c24 2>/dev/null; cd $E/c24
printf 'a=1\n' > a.py; G add -A; G commit -qm base; git push -q origin main 2>/dev/null
rm -rf $E/c24-other; git clone -q $E/c24-remote $E/c24-other 2>/dev/null; (cd $E/c24-other && for i in 1 2 3; do printf "u=$i\n" > up$i.py; git add -A; git -c user.email=t@t -c user.name=t commit -qm up$i; done; git push -q origin main 2>/dev/null)
git fetch -q origin; git remote set-head origin -d 2>/dev/null; git switch -q -c feat origin/main; printf 'f=1\n' > feat.py; G add -A; G commit -qm feat
O=$($PY $S inspect . 2>&1)
check c24-origin "grep -q 'default_branch=origin/main' <<<\"\$O\" && grep -q 'scope_files=1' <<<\"\$O\""

# 25 review r3: an unknown --base is reported
cd $E/c2; O=$($PY $S inspect . --base develp 2>&1)
check c25-bad-base "grep -q '^note=base develp not found' <<<\"\$O\""

# 26 review r4: a real Python syntax error is not blamed on the interpreter
R=$E/c26; newrepo $R; cd $R; printf 'def g(:\n    pass\n' > bad.py
O=$($PY $S analyze . bad.py 2>&1)
check c26-syntax "grep -q '^finding=bad.py:1 SYNTAX' <<<\"\$O\" && ! grep -q 'this Python cannot parse it' <<<\"\$O\""

# 27 review r4: detached HEAD says branch commits were not compared
cd $E/c2; git checkout -q --detach HEAD; O=$($PY $S inspect . 2>&1); git checkout -q feat
check c27-detached "grep -q '^note=detached HEAD' <<<\"\$O\""

# 28 review r5: detached HEAD honours --base; a repo without commits is not "detached"
cd $E/c2; git checkout -q --detach HEAD; O=$($PY $S inspect . --base main 2>&1); git checkout -q feat
check c28-detached-base "grep -q 'scope_from=branch-since-main:2' <<<\"\$O\""
R=$E/c28; newrepo $R; cd $R; printf 'x=1\n' > a.py; O=$($PY $S inspect . 2>&1)
check c28-no-commits "! grep -q 'detached HEAD' <<<\"\$O\" && grep -q 'scope_files=1' <<<\"\$O\""

# 29 review r13: default branch without upstream compares with origin/<branch> or says why not
R=$E/c29; newrepo $R; cd $R; printf 'a=1\n' > a.py; G add -A; G commit -qm one; printf 'b=1\n' > b.py; G add -A; G commit -qm two
O=$($PY $S inspect . 2>&1)
check c29-no-upstream-note "grep -q '^note=main has no upstream' <<<\"\$O\""
# 30 review r13: dirty count lists files inside new folders
R=$E/c30; newrepo $R; cd $R; mkdir -p src tests; printf 'x=1\n' > src/a.py; printf 'x=1\n' > src/b.py; printf 'x=1\n' > tests/test_a.py
O=$($PY $S inspect . 2>&1)
check c30-dirty "grep -q '^git=dirty:3' <<<\"\$O\""

# 31 review r21: ruff noqa handling follows SonarQube
R=$E/c31; mkdir -p $R; cd $R; printf '# flake8: noqa\nimport os\n' > filelevel.py; printf 'def f():\n    try:\n        g()\n    except:  # noqa: E722\n        pass\n' > coded.py
O=$($PY $S analyze . filelevel.py coded.py 2>&1)
check c31-file-level-noqa "grep -q '^finding=filelevel.py:2 S1128' <<<\"\$O\""
check c31-ruff-code-noqa "grep -q '^finding=coded.py:4 S5754' <<<\"\$O\""

# 32 review r30: a suppressed S5754 does not also hide the broad-catch decision
R=$E/c32; mkdir -p $R; cd $R; printf 'def f():\n    try:\n        g()\n    except BaseException:  # NOSONAR(S5754)\n        log()\n' > m.py
O=$($PY $S analyze . m.py 2>&1)
check c32-broad-except-kept "grep -q '^finding=m.py:4 BROAD-EXCEPT ask' <<<\"\$O\""
check c32-s5754-suppressed "! grep -q '^finding=m.py:4 S5754' <<<\"\$O\""

echo "TOTAL pass=$PASS fail=$FAIL"
[ $FAIL -eq 0 ]
